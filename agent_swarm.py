"""Multi-Agent Swarm for DarkShadow.

Provides specialized autonomous background workers:
1. DeepResearchAgent: Multi-step web research, synthesis, and Markdown report generation.
2. WorkspaceAuditorAgent: Project health, git status, and environment audit.
3. SystemCleanupAgent: Safe temp/cache file scanner and reclaimable space optimizer.
4. SwarmCoordinator: Central dispatcher managing the swarm lifecycle.
"""

from __future__ import annotations

import datetime
import logging
import os
import re
import shutil
import subprocess
import threading
import uuid
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable

LOGGER = logging.getLogger(__name__)

REPORTS_DIR = Path(".darkshadow/reports")


@dataclass
class SwarmAgentReport:
    """Standardized output from any swarm worker agent."""

    agent_id: str
    agent_name: str
    role: str
    success: bool
    summary: str
    details: dict[str, Any] = field(default_factory=dict)
    report_file: str | None = None
    completed_at: str = field(default_factory=lambda: datetime.datetime.now().isoformat())


class DeepResearchAgent:
    """Autonomous agent that investigates complex topics and produces Markdown research reports."""

    def __init__(self, topic: str, gemini_client: Any = None, tavily_key: str | None = None) -> None:
        self.topic = topic
        self.gemini_client = gemini_client
        self.tavily_key = tavily_key
        self.agent_id = f"research_{uuid.uuid4().hex[:6]}"

    def run(self) -> SwarmAgentReport:
        """Execute multi-step research pipeline."""
        LOGGER.info("[%s] Starting deep research on '%s'", self.agent_id, self.topic)
        REPORTS_DIR.mkdir(parents=True, exist_ok=True)

        # 1. Decompose topic into sub-queries
        sub_queries = [
            f"{self.topic} latest developments overview",
            f"{self.topic} practical applications and architecture",
            f"{self.topic} future trends and benchmarks",
        ]

        # 2. Gather information via RealtimeInfoService / Tavily
        gathered_content: list[dict[str, Any]] = []
        try:
            from realtimeinfo import RealtimeInfoService
            from config import load_settings
            settings = load_settings()
            info_svc = RealtimeInfoService(settings=settings)

            for q in sub_queries:
                try:
                    res = info_svc.answer(q)
                    if res and res.display_text and not res.error:
                        sources = [{"title": s.title, "url": s.url} for s in res.sources] if res.sources else []
                        gathered_content.append({"query": q, "answer": res.display_text, "sources": sources})
                except Exception as q_exc:
                    LOGGER.debug("Search query failed for '%s': %s", q, q_exc)
        except Exception as exc:
            LOGGER.warning("Research gathering error: %s", exc)

        # 3. Synthesize Report
        timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        sanitized_topic = re.sub(r"[^a-zA-Z0-9_\-]+", "_", self.topic.strip().lower())[:30]
        report_path = REPORTS_DIR / f"research_{sanitized_topic}_{timestamp}.md"

        report_md = self._generate_markdown(gathered_content)
        try:
            with open(report_path, "w", encoding="utf-8") as f:
                f.write(report_md)
        except Exception as write_exc:
            LOGGER.warning("Failed to save report: %s", write_exc)

        summary_text = (
            f"Captain, '{self.topic}' par deep research complete ho gayi hai. "
            f"Report save ho chuki hai: {report_path.name}"
        )

        return SwarmAgentReport(
            agent_id=self.agent_id,
            agent_name="DeepResearchAgent",
            role="Research Specialist",
            success=True,
            summary=summary_text,
            details={"topic": self.topic, "sections_analyzed": len(gathered_content)},
            report_file=str(report_path),
        )

    def _generate_markdown(self, content_list: list[dict[str, Any]]) -> str:
        """Create structured markdown report."""
        now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        lines = [
            f"# Deep Research Report: {self.topic}",
            f"**Generated by:** DarkShadow Swarm (DeepResearchAgent)",
            f"**Date:** {now_str}",
            "---",
            "",
            "## Executive Summary",
            f"Comprehensive analysis and investigation of **{self.topic}** covering foundational concepts, recent advancements, and practical implications.",
            "",
        ]

        if content_list:
            lines.append("## Findings & Key Data")
            for idx, item in enumerate(content_list, 1):
                lines.append(f"### {idx}. Focus Area: {item['query']}")
                lines.append(f"{item['answer']}\n")
                if item.get("sources"):
                    lines.append("**Sources:**")
                    for s in item["sources"]:
                        lines.append(f"- [{s.get('title', 'Reference')}]({s.get('url', '#')})")
                    lines.append("")
        else:
            lines.append("## Summary")
            lines.append(f"Preliminary assessment compiled for {self.topic}. Detailed insights cataloged in DarkShadow memory.")

        lines.append("---")
        lines.append("*Report generated autonomously by DarkShadow Next-Gen Swarm.*")
        return "\n".join(lines)


class WorkspaceAuditorAgent:
    """Audits local git repository, virtual environment, and active file health."""

    def __init__(self, workspace_path: Path | str = ".") -> None:
        self.workspace_path = Path(workspace_path).resolve()
        self.agent_id = f"auditor_{uuid.uuid4().hex[:6]}"

    def run(self) -> SwarmAgentReport:
        """Run health checks on the workspace."""
        LOGGER.info("[%s] Auditing workspace at %s", self.agent_id, self.workspace_path)
        details: dict[str, Any] = {}

        # 1. Git status check
        git_branch = "unknown"
        git_status_lines = []
        try:
            branch_out = subprocess.run(
                ["git", "rev-parse", "--abbrev-ref", "HEAD"],
                cwd=str(self.workspace_path),
                capture_output=True,
                text=True,
                timeout=5,
            )
            if branch_out.returncode == 0:
                git_branch = branch_out.stdout.strip()

            status_out = subprocess.run(
                ["git", "status", "--short"],
                cwd=str(self.workspace_path),
                capture_output=True,
                text=True,
                timeout=5,
            )
            if status_out.returncode == 0:
                git_status_lines = [line for line in status_out.stdout.strip().splitlines() if line]
        except Exception as git_exc:
            LOGGER.debug("Git audit notice: %s", git_exc)

        details["git_branch"] = git_branch
        details["uncommitted_changes_count"] = len(git_status_lines)

        # 2. Virtual Environment check
        venv_active = (self.workspace_path / ".venv").exists()
        details["venv_present"] = venv_active

        # 3. Generate summary
        summary = (
            f"Captain, workspace audit complete: Git branch '{git_branch}' par {len(git_status_lines)} uncommitted changes hain. "
            f"Virtual environment: {'Available (.venv)' if venv_active else 'Not found'}."
        )

        return SwarmAgentReport(
            agent_id=self.agent_id,
            agent_name="WorkspaceAuditorAgent",
            role="Codebase & Repo Auditor",
            success=True,
            summary=summary,
            details=details,
        )


class SystemCleanupAgent:
    """Scans cache files, temporary directories, and calculates reclaimable space."""

    def __init__(self, target_dir: Path | str = ".", dry_run: bool = True) -> None:
        self.target_dir = Path(target_dir).resolve()
        self.dry_run = dry_run
        self.agent_id = f"cleaner_{uuid.uuid4().hex[:6]}"

    def run(self) -> SwarmAgentReport:
        """Scan or clean cache files."""
        LOGGER.info("[%s] Scanning cleanup targets (dry_run=%s)", self.agent_id, self.dry_run)
        reclaimable_bytes = 0
        cleaned_dirs = []

        # Scan for __pycache__ and .pytest_cache
        for root, dirs, _ in os.walk(str(self.target_dir)):
            for d in list(dirs):
                if d in {"__pycache__", ".pytest_cache"}:
                    p = Path(root) / d
                    try:
                        dir_size = sum(f.stat().st_size for f in p.rglob("*") if f.is_file())
                        reclaimable_bytes += dir_size
                        if not self.dry_run:
                            shutil.rmtree(p, ignore_errors=True)
                            cleaned_dirs.append(str(p))
                        else:
                            cleaned_dirs.append(str(p))
                    except Exception as e:
                        LOGGER.debug("Cleanup scan error for %s: %s", p, e)

        mb_reclaimed = reclaimable_bytes / (1024 * 1024)
        if self.dry_run:
            summary = (
                f"Captain, cleanup scan me {len(cleaned_dirs)} cache directories mili hain "
                f"({mb_reclaimed:.2f} MB reclaimable). Confirm karne par main ise safe delete kar dunga."
            )
        else:
            summary = (
                f"Captain, {len(cleaned_dirs)} cache folders successfully clean kar diye gaye hain. "
                f"{mb_reclaimed:.2f} MB storage reclaim ho gayi!"
            )

        return SwarmAgentReport(
            agent_id=self.agent_id,
            agent_name="SystemCleanupAgent",
            role="Storage Optimizer",
            success=True,
            summary=summary,
            details={"folders_count": len(cleaned_dirs), "reclaimable_mb": round(mb_reclaimed, 2), "dry_run": self.dry_run},
        )


class SwarmCoordinator:
    """Orchestrates multi-agent swarm tasks in parallel background threads."""

    _instance: SwarmCoordinator | None = None
    _lock = threading.Lock()

    def __init__(self) -> None:
        self._active_reports: dict[str, SwarmAgentReport] = {}

    @classmethod
    def get_instance(cls) -> SwarmCoordinator:
        """Singleton accessor."""
        with cls._lock:
            if cls._instance is None:
                cls._instance = cls()
            return cls._instance

    def dispatch_agent(self, agent_fn: Callable[[], SwarmAgentReport], task_name: str) -> str:
        """Dispatch a swarm agent in the background and notify upon completion."""
        from background_agent import BackgroundAgentManager

        bg_mgr = BackgroundAgentManager.get_instance()

        def _worker() -> dict[str, Any]:
            report = agent_fn()
            with self._lock:
                self._active_reports[report.agent_id] = report
            return {
                "agent_id": report.agent_id,
                "message": report.summary,
                "report_file": report.report_file,
            }

        task_id = bg_mgr.dispatch(name=task_name, func=_worker)
        return task_id

    def run_research(self, topic: str) -> str:
        """Dispatch DeepResearchAgent for a topic."""
        agent = DeepResearchAgent(topic=topic)
        return self.dispatch_agent(agent.run, task_name=f"DeepResearch: {topic[:25]}")

    def run_workspace_audit(self) -> str:
        """Dispatch WorkspaceAuditorAgent."""
        agent = WorkspaceAuditorAgent()
        return self.dispatch_agent(agent.run, task_name="WorkspaceAudit")

    def run_cleanup(self, dry_run: bool = True) -> str:
        """Dispatch SystemCleanupAgent."""
        agent = SystemCleanupAgent(dry_run=dry_run)
        return self.dispatch_agent(agent.run, task_name="SystemCleanup")


